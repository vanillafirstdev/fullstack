<h1>About this kit</h1>
<p>Every file here is read by the browser or by PHP exactly as written. There is no
   <code>node_modules</code>, no <code>vendor/</code> and no compile step between your editor and the page.</p>
<p>Start in <code>public/index.php</code>: it registers the routes. Each route calls a method in
   <code>app/Controllers/</code>, which renders a template from <code>app/views/pages/</code>
   inside <code>app/views/layouts/app.php</code>.</p>
